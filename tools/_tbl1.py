import re
d = open('../firmware/appFw-2.00.so','rb').read()
pats = {
  'a7c2 full 12': bytes([0x00,0x03,0x02,0x01,0x10,0x0f,0x11,0x12,0x05,0x0d,0x13,0x14]),
  'a7c2 first 9': bytes([0x00,0x03,0x02,0x01,0x10,0x0f,0x11,0x12,0x05]),
  'a7c2 first 5': bytes([0x00,0x03,0x02,0x01,0x10]),
  'a7c2 first 4': bytes([0x00,0x03,0x02,0x01]),
}
for name, p in pats.items():
    offs = [m.start() for m in re.finditer(re.escape(p), d)]
    print('%-14s %d %s' % (name, len(offs), ' '.join(hex(o) for o in offs[:10])))